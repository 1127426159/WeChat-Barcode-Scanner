#!/usr/bin/env python3
"""Build the cross-platform server package and embed it in the mini program."""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist" / "release"
EMBED_DIR = ROOT / "miniprogram" / "assets" / "server"
EMBED_MODULE = "package-data.js"
PACKAGE_NAME = "WeChat-Barcode-Scanner.zip"
ROOT_NAME = "WeChat-Barcode-Scanner"
LEGACY_EMBEDDED_FILES = (
    "WeChat-Barcode-Scanner.zip",
    "WeChat-Barcode-Scanner-windows.zip",
    "WeChat-Barcode-Scanner-macos.tar.gz",
)


def read_version() -> str:
    text = (ROOT / "host" / "__init__.py").read_text(encoding="utf-8")
    match = re.search(r'__version__\s*=\s*"([^"]+)"', text)
    if not match:
        raise RuntimeError("Could not read host/__init__.py version")
    return match.group(1)


def package_files() -> list:
    files = [
        "README.md",
        "QUICKSTART.txt",
        "MACOS-无法打开请看.txt",
        "THIRD_PARTY_NOTICES.md",
        "LICENSE",
        "CHANGELOG.md",
        "requirements.txt",
        "START-FOR-WINDOWS.bat",
        "START-FOR-MAC.command",
        "start.bat",
        "bootstrap.bat",
        "setup_windows.cmd",
        "install_python.ps1",
        "start.sh",
        "bootstrap.sh",
        "setup_env.sh",
        "start-mac.command",
    ]
    files.extend(
        path.relative_to(ROOT).as_posix()
        for path in sorted((ROOT / "host").glob("*.py"))
    )
    files.extend(
        path.relative_to(ROOT).as_posix()
        for path in sorted((ROOT / "docs" / "images").glob("*"))
        if path.is_file()
    )
    files.extend(
        path.relative_to(ROOT).as_posix()
        for path in sorted((ROOT / "licenses").glob("*"))
        if path.is_file()
    )
    return files


def is_executable(relative: str) -> bool:
    return Path(relative).suffix in (".sh", ".command")


def write_package(output: Path) -> None:
    with zipfile.ZipFile(
        output, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9
    ) as archive:
        for relative in package_files():
            data = (ROOT / relative).read_bytes()
            info = zipfile.ZipInfo(ROOT_NAME + "/" + relative, (2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            mode = 0o100755 if is_executable(relative) else 0o100644
            info.external_attr = mode << 16
            archive.writestr(info, data)


def checksum(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build() -> tuple:
    version = read_version()
    DIST.mkdir(parents=True, exist_ok=True)
    package = DIST / PACKAGE_NAME
    write_package(package)
    package.with_name(package.name + ".sha256").write_text(
        checksum(package) + "  " + package.name + "\n",
        encoding="ascii",
    )
    return version, package


def sync_miniprogram(version: str, package: Path) -> None:
    EMBED_DIR.mkdir(parents=True, exist_ok=True)
    for name in LEGACY_EMBEDDED_FILES:
        legacy = EMBED_DIR / name
        if legacy.exists():
            legacy.unlink()
    encoded = base64.b64encode(package.read_bytes()).decode("ascii")
    chunks = [encoded[index : index + 8000] for index in range(0, len(encoded), 8000)]
    module_text = (
        "// Generated by tools/build_server_packages.py. Do not edit.\n"
        "const PACKAGE_BASE64 = [\n"
        + ",\n".join('  "' + chunk + '"' for chunk in chunks)
        + "\n].join(\"\");\n\nmodule.exports = PACKAGE_BASE64;\n"
    )
    (EMBED_DIR / EMBED_MODULE).write_text(module_text, encoding="ascii")
    manifest = {
        "version": version,
        "package": PACKAGE_NAME,
        "module": EMBED_MODULE,
        "encoding": "base64",
        "sha256": checksum(package),
    }
    (EMBED_DIR / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def check_embedded(version: str) -> None:
    manifest_path = EMBED_DIR / "manifest.json"
    if not manifest_path.exists():
        raise RuntimeError("Embedded server manifest is missing")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("version") != version:
        raise RuntimeError(
            "Embedded server version {} does not match host version {}".format(
                manifest.get("version"), version
            )
        )
    if manifest.get("package") != PACKAGE_NAME:
        raise RuntimeError("Embedded server manifest has the wrong package name")
    if manifest.get("module") != EMBED_MODULE:
        raise RuntimeError("Embedded server module name is incorrect")
    module_path = EMBED_DIR / EMBED_MODULE
    if not module_path.exists() or module_path.stat().st_size == 0:
        raise RuntimeError("Embedded server module is missing")
    module_text = module_path.read_text(encoding="ascii")
    encoded = "".join(re.findall(r'"([A-Za-z0-9+/=]+)"', module_text))
    try:
        decoded = base64.b64decode(encoded)
    except ValueError:
        raise RuntimeError("Embedded server module is not valid Base64")
    actual = hashlib.sha256(decoded).hexdigest()
    if actual != manifest.get("sha256"):
        raise RuntimeError("Embedded server module checksum does not match")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--sync-miniprogram",
        action="store_true",
        help="copy the generated package into miniprogram/assets/server",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="check that the embedded package matches the host version",
    )
    args = parser.parse_args(argv)
    version = read_version()
    if args.check:
        check_embedded(version)
        print("Embedded server package is ready for version " + version)
        return 0
    version, package = build()
    if args.sync_miniprogram:
        sync_miniprogram(version, package)
        print("Embedded package synced to " + str(EMBED_DIR))
    print("Built " + str(package))
    return 0


if __name__ == "__main__":
    sys.exit(main())
